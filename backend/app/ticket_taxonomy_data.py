def _normalized_phrase(value: str) -> str:
    return value.replace("_", " ").strip()


def _unique(values: tuple[str, ...]) -> tuple[str, ...]:
    return tuple(dict.fromkeys(_normalized_phrase(value) for value in values if _normalized_phrase(value)))


def _taxonomy_v2_as_rules(rules: tuple[TaxonomyRuleV2, ...]) -> tuple[TaxonomyRule, ...]:
    return tuple(
        TaxonomyRule(
            name=rule.name,
            description=rule.description,
            patterns=_unique(rule.includes),
            category_aliases=_unique(rule.contexts + rule.assignment_hints),
            excludes=_unique(rule.excludes),
        )
        for rule in rules
    )


DEFAULT_TAXONOMY = _taxonomy_v2_as_rules(DEFAULT_TAXONOMY_V2)
