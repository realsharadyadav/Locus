from dataclasses import dataclass


@dataclass(frozen=True)
class TaxonomyRule:
    """A configurable parent pain point and the child signals that roll up to it.

    Add a rule or extend ``patterns`` to evolve the taxonomy. The grouping engine
    intentionally knows nothing about individual datasets, ticket IDs, or counts.
    """

    name: str
    description: str
    patterns: tuple[str, ...]
    category_aliases: tuple[str, ...] = ()
    excludes: tuple[str, ...] = ()


